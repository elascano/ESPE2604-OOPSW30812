    private void btnSortActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSortActionPerformed
    try {
            String input = txtInputNumbers.getText().trim();
            if (input.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter numbers.");
                return;
            }

            String[] parts = input.split(",");
            if (parts.length <= 1) {
                JOptionPane.showMessageDialog(this, "Size must be greater than 1.");
                return;
            }

            int[] data = new int[parts.length];
            for (int i = 0; i < parts.length; i++) {
                data[i] = Integer.parseInt(parts[i].trim());
            }

            NumberArray result = controller.processAndSave(data);

            lblAlgorithm.setText(result.getAlgorithm());
            lblSortedResult.setText(result.getSorted());

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid input. Please enter valid integers separated by commas.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSortActionPerformed

