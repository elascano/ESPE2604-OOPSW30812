    private void btnsortActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnsortActionPerformed
        try {
            String input = txtnumberEntry.getText().trim();
            if (input.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Please enter numbers.");
                return;
            }

            SortingRecord result = controller.processAndSort(input);

            lblresultAlgorthmUsed.setText(result.getSortAlgorithm());
            lblresultResult.setText(result.getSorted());

            try {
                JsonFileWriter.appendRecord(result);
            } catch (IOException ioEx) {
                logger.log(java.util.logging.Level.WARNING, "No se pudo guardar el resultado en el archivo JSON", ioEx);
                JOptionPane.showMessageDialog(this,
                        "El ordenamiento se realizó correctamente, pero no se pudo guardar en el archivo JSON: " + ioEx.getMessage(),
                        "Aviso", JOptionPane.WARNING_MESSAGE);
            }

        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        } catch (Exception e) {
            logger.log(java.util.logging.Level.SEVERE, null, e);
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnsortActionPerformed

